import assert from 'node:assert/strict';
import {createAccountBoundary} from '../lib/account-boundary.js';
const guard=createAccountBoundary();
const first=guard.begin();
assert.equal(guard.observe('account-a'),false);
assert.equal(guard.verify(first,'account-a'),true);
assert.equal(guard.observe('account-a'),false,'Same-account token refresh must not reset the view');
assert.equal(guard.current(first),true);
assert.equal(guard.observe('account-b'),true);
assert.equal(guard.current(first),false,'Late wallet response must be discarded');
assert.equal(guard.verify(first,'account-a'),false);
const second=guard.begin();
assert.equal(guard.verify(second,'account-a'),false,'Verified response must match observed identity');
assert.equal(guard.verify(second,'account-b'),true);
assert.equal(guard.observe(null),true);
assert.equal(guard.current(second),false,'Sign-out invalidates pending reads');
const third=guard.begin();guard.invalidate();
assert.equal(guard.current(third),false,'Unmount invalidates pending reads');
const fourth=guard.begin();guard.begin();
assert.equal(guard.current(fourth),false,'Retry invalidates older reads');
console.log('Account boundary: 13 checks passed.');
