import assert from 'node:assert/strict';
import {buildMonthlyPlan} from '../lib/monthly-plan.js';
const categories=[{key:'general'},{key:'dining'},{key:'international'}];
const wallet=[{card_name:'Alpha'},{card_name:'Beta'}];
const base={card_name:'Alpha',category:'general',channel:'any',value_rate_percent:1};
const run=(rules,spend,w=wallet)=>buildMonthlyPlan({wallet:w,rules,spend,categories});
let plan=run([{...base,cap_amount:100}],{general:1000});
assert.equal(plan.coveredSpend,100);
assert.equal(plan.unmodeledSpend,900);
assert.equal(plan.optimized,1);
assert.equal(plan.annualIncremental,0);
plan=run([base],{general:Infinity,dining:-10});
assert.equal(plan.monthlySpend,0);
assert.equal(plan.baseline,null);
plan=run([{...base,channel:'domestic'},{...base,card_name:'Beta',category:'international',value_rate_percent:2}],{general:1000,international:1000});
assert.equal(plan.optimized,30);
assert.equal(plan.annualIncremental,null);
plan=run([base,{...base,card_name:'Beta',category:'dining',value_rate_percent:2}],{general:1000,dining:1000});
assert.equal(plan.annualIncremental,120);
assert.equal(plan.baseline.card.card_name,'Alpha');
plan=run([],{general:1000});
assert.equal(plan.unmodeledSpend,1000);
assert.equal(plan.annualIncremental,null);
console.log('Monthly plan: 12 checks passed.');
