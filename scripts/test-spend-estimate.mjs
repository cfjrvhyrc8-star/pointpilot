import assert from 'node:assert/strict';
import {selectSpendRule,spendValue,spendCardMatches} from '../lib/spend-estimate.js';
const base={card_name:'Diners Club Black Metal',category:'general',channel:'any',value_rate_percent:3.3333,active:true};
const bonus={...base,category:'dining',channel:'weekend',value_rate_percent:6.6667};
const pick=(rules,category='dining',amount=15000)=>selectSpendRule(base.card_name,category,rules,amount);
assert.equal(pick([base,bonus]),base);
assert.equal(pick([bonus]),undefined);
assert.equal(pick([{...base,channel:'smartbuy'}],'flights'),undefined);
assert.equal(pick([{...base,channel:'domestic'}],'international'),undefined);
assert.equal(pick([{...base,channel:'domestic'}],'general').channel,'domestic');
for(const value of [null,undefined,-1,Infinity,NaN])assert.equal(pick([{...base,value_rate_percent:value}]),undefined);
assert.equal(pick([{...base,active:false}]),undefined);
assert.equal(pick([{...base,cap_amount:-1}]),undefined);
assert.equal(pick([base],'general',Infinity),undefined);
assert.equal(spendCardMatches('Diners Club Black','Diners Club Black Metal'),false);
assert.equal(spendCardMatches('HDFC Diners Club Black Metal Edition Credit Card',base.card_name),true);
assert.equal(spendCardMatches('',''),false);
const capped={...base,value_rate_percent:10,cap_amount:100};
assert.equal(pick([base,capped],'general',10000),base);
assert.equal(spendValue(capped,1000).value,10);
assert.equal(spendValue(capped,1000).unrewardedSpend,900);
assert.equal(pick([base,{...base,category:'dining',value_rate_percent:null}]),base);
console.log('Spend estimates: 20 checks passed.');
