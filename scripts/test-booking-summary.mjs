import assert from 'node:assert/strict';
import {bookingSummary,bookingDecisionText} from '../lib/booking-summary.js';
const rows=[{kind:'cash',total:10000},{kind:'direct',total:8000},{kind:'award',total:9000}];
const summary=bookingSummary({complete:true,rows});
assert.equal(summary.best.kind,'direct');
assert.equal(summary.margin,1000);
assert.equal(summary.saving,2000);
assert.equal(summary.tied,false);
assert.equal(summary.checks.length,3);
assert.equal(rows[0].kind,'cash');
assert.equal(bookingSummary({complete:false,rows}),null);
assert.equal(bookingSummary(null),null);
assert.equal(bookingSummary({complete:true,rows:[]}),null);
assert.equal(bookingSummary({complete:true,rows:[{total:Infinity}]}),null);
const tie=bookingSummary({complete:true,rows:[{kind:'award',total:10000},{kind:'cash',total:10000}]});
assert.equal(tie.best.kind,'cash');
assert.equal(tie.tied,true);
assert.equal(tie.saving,0);
assert.equal(bookingSummary({complete:true,rows:[rows[0]]}).margin,null);
assert.match(bookingSummary({complete:true,rows:[{kind:'award',total:1},rows[0]]}).checks[0],/award seats/);
console.log('Booking summary: 15 checks passed.');
const exportModel={complete:true,rows:[{kind:'cash',cash:10000,pointsValue:0,total:10000},{kind:'direct',cash:3000,pointsValue:5000,total:8000}]};
const report=bookingDecisionText(exportModel,'funding',new Date('2026-10-15T00:00:00Z'));
assert.match(report,/cash payable INR 3000.00; points value given up INR 5000.00; modeled cost INR 8000.00/);
assert.match(report,/saving versus cash: INR 2000.00/);
assert.match(report,/Airline award excluded: mileage target/);
assert.match(report,/Not a booking offer/);
assert.match(report,/does not identify an itinerary/);
assert.match(report,/2026-10-15T00:00:00.000Z/);
assert.equal(bookingDecisionText({...exportModel,complete:false}),null);
assert.equal(bookingDecisionText({complete:true,rows:[{kind:'cash',total:1}]}),null);
assert.equal(bookingDecisionText(null),null);
const tied={complete:true,rows:exportModel.rows.map(row=>({...row,total:10000}))};
assert.match(bookingDecisionText(tied),/leading options are tied/);
assert.match(bookingDecisionText(exportModel,'verification'),/rules or limits need verification/);
console.log('Decision summary export: 11 checks passed.');
