import assert from 'node:assert/strict';
import {bookingSummary} from '../lib/booking-summary.js';
const rows=[{kind:'cash',total:10000},{kind:'direct',total:8000},{kind:'award',total:9000}];
const summary=bookingSummary({complete:true,rows});
assert.equal(summary.best.kind,'direct');
assert.equal(summary.margin,1000);
assert.equal(summary.saving,2000);
assert.equal(summary.tied,false);
assert.equal(summary.checks.length,3);
assert.equal(rows[0].kind,'cash');
assert.equal(bookingSummary({complete:false,rows}),null);
assert.equal(bookingSummary(null),null);
assert.equal(bookingSummary({complete:true,rows:[]}),null);
assert.equal(bookingSummary({complete:true,rows:[{total:Infinity}]}),null);
const tie=bookingSummary({complete:true,rows:[{kind:'award',total:10000},{kind:'cash',total:10000}]});
assert.equal(tie.best.kind,'cash');
assert.equal(tie.tied,true);
assert.equal(tie.saving,0);
assert.equal(bookingSummary({complete:true,rows:[rows[0]]}).margin,null);
assert.match(bookingSummary({complete:true,rows:[{kind:'award',total:1},rows[0]]}).checks[0],/award seats/);
