import assert from 'node:assert/strict';
import {buildBookingDecision,buildPersonalValue} from '../lib/booking-decision.js';
const base={cashFare:100000,taxes:10000,award:{target:50000,shortfall:0,routes:[]},direct:{rule:{route_status:'verified'},cashRemaining:30000,pointsUsed:70000}};
assert.equal(buildBookingDecision(base).lowest.kind,'award');
assert.equal(buildBookingDecision(base).awardValue,1.8);
assert.equal(buildBookingDecision({...base,award:{...base.award,shortfall:1}}).lowest.kind,'direct');
assert.equal(buildBookingDecision({...base,award:{...base.award,routes:[{contribution:1,rule:{route_status:'draft'}}]}}).reason,'verification');
assert.equal(buildBookingDecision({...base,taxes:120000,direct:null}).lowest.kind,'cash');
assert.equal(buildBookingDecision({...base,taxes:100000,direct:null}).lowest.kind,'cash');
assert.equal(buildBookingDecision({...base,cashFare:0}),null);
assert.equal(buildBookingDecision({...base,taxes:-1}),null);
assert.equal(buildBookingDecision({...base,award:{target:0,routes:[],shortfall:0},direct:null}).lowest.kind,'cash');
assert.equal(buildBookingDecision({...base,award:{...base.award,routes:[{contribution:1,rule:{route_status:'verified',active:false}}]}}).awardEligible,false);
console.log('Booking decision: 9 scenarios passed.');
const card={id:'one',card_name:'Test card'};
const personalAward={...base.award,program:{code:'test',name:'Test miles'},existing:10000,routes:[{card,pointsNeeded:80000,contribution:40000,rule:{route_status:'verified'}}]};
const personalDirect={...base.direct,card};
const decision=buildBookingDecision({...base,direct:personalDirect,award:personalAward});
const calc=values=>buildPersonalValue({decision,direct:personalDirect,award:personalAward,values});
assert.equal(calc({}).complete,false);
assert.equal(calc({}).best,null);
const valued=calc({'card:one':0.5,'miles:test':1});
assert.equal(valued.requirements.length,2);
assert.equal(valued.rows.find(r=>r.kind==='award').total,60000);
assert.equal(valued.rows.find(r=>r.kind==='direct').total,65000);
assert.equal(valued.best.kind,'award');
assert.equal(calc({'card:one':2,'miles:test':2}).best.kind,'cash');
assert.equal(calc({'card:one':0,'miles:test':0}).best.kind,'award');
for(const invalid of ['',-1,'Infinity','abc'])assert.equal(calc({'card:one':invalid,'miles:test':1}).complete,false);
console.log('Personal value: 12 assertions passed, including no double-counted transferred miles.');
const feeDecision=buildBookingDecision({...base,extraFees:{cash:100,direct:500,award:250,transfer:750}});
assert.equal(feeDecision.choices.find(row=>row.kind==='cash').cash,100100);
assert.equal(feeDecision.choices.find(row=>row.kind==='direct').cash,30500);
assert.equal(feeDecision.choices.find(row=>row.kind==='award').cash,11000);
assert.equal(feeDecision.cashSaved,89100);
assert.equal(feeDecision.awardValue,1.782);
assert.equal(buildBookingDecision({...base,extraFees:{transfer:25000}}).lowest.kind,'direct');
for(const invalid of ['',-1,'Infinity','abc'])assert.equal(buildBookingDecision({...base,extraFees:{cash:invalid}}),null);
const feePersonal=buildPersonalValue({decision:buildBookingDecision({...base,direct:personalDirect,award:personalAward,extraFees:{award:1000,transfer:5000}}),direct:personalDirect,award:personalAward,values:{'card:one':0.5,'miles:test':1}});
assert.equal(feePersonal.rows.find(row=>row.kind==='award').total,66000);
assert.equal(feePersonal.best.kind,'direct');
assert.equal(buildBookingDecision({...base,extraFees:{cash:0.25}}).choices.find(row=>row.kind==='cash').cash,100000.25);
console.log('Fee comparison: 13 assertions passed, including ranking changes and invalid input.');
